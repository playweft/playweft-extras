import test from 'node:test';
import assert from 'node:assert/strict';

test('bridge buffers pre-initialize state, deduplicates versions, resets per match and bounds pending work', async () => {
  const windowStub = new EventTarget();
  windowStub.parent = windowStub;
  globalThis.window = windowStub;
  const { PlayweftBridge } = await import('../src/playweft-client.js');
  const bridge = new PlayweftBridge();
  const requests = [];
  const fakePort = { postMessage: (m) => requests.push(m), start() {}, close() {} };
  const snapshots = [];
  bridge.addEventListener('state', (event) => snapshots.push(event.detail));
  bridge.onWindowMessage({ source: {}, data: { type: 'playweft:bridge', version: 1 }, ports: [fakePort] });
  assert.equal(bridge.port, null);
  bridge.onWindowMessage({ source: windowStub, data: { type: 'playweft:bridge', version: 1 }, ports: [fakePort] });
  assert.equal(requests[0].method, 'game.initialize');
  const snapshot = (version, matchId = 'm1') => ({ jsonrpc: '2.0', method: 'game.state', params: { state: { round: 1 }, version, matchId } });
  bridge.receive(snapshot(2));
  assert.equal(snapshots.length, 0);
  bridge.receive({ jsonrpc: '2.0', id: requests[0].id, result: { mode: 'room', playerId: 'p1' } });
  await Promise.resolve();
  assert.equal(snapshots.length, 1);
  bridge.receive(snapshot(2)); bridge.receive(snapshot(1));
  assert.equal(snapshots.length, 1);
  bridge.receive(snapshot(3)); bridge.receive(snapshot(0, 'm2'));
  assert.equal(snapshots.length, 3);
  const action = bridge.action({ type: 'turn', direction: 1, round: 1 });
  const request = requests.at(-1);
  assert.equal(request.method, 'room.action');
  assert.deepEqual(request.params.action, { type: 'turn', direction: 1, round: 1 });
  bridge.receive({ jsonrpc: '2.0', id: request.id, result: { accepted: true } });
  assert.deepEqual(await action, { accepted: true });
  const outstanding = Array.from({ length: 8 }, () => bridge.call('room.action', {}).catch((e) => e.message));
  await assert.rejects(bridge.call('room.action', {}), /Too many pending/);
  bridge.close();
  assert.equal(bridge.pending.size, 0);
  await Promise.all(outstanding);
  delete globalThis.window;
});

test('storage waits for initialize, advertises support, preserves errors and closes pending readiness', async () => {
  const host = new EventTarget(); host.parent = host;
  globalThis.window = host;
  const { PlayweftBridge } = await import('../src/playweft-client.js');
  const bridge = new PlayweftBridge(), messages = [];
  const port = { postMessage: message => messages.push(message), start() {}, close() {} };
  const ready = bridge.ready();
  const read = bridge.localStorage.getItem('save');
  bridge.onWindowMessage({ source: host, data: { type: 'playweft:bridge', version: 1 }, ports: [port] });
  bridge.receive({ jsonrpc: '2.0', id: messages[0].id, result: { capabilities: ['localStorage.getItem', 'localStorage.setItem'] } });
  await ready; await Promise.resolve();
  const request = messages.at(-1);
  assert.equal(request.method, 'localStorage.getItem');
  assert.deepEqual(request.params, { key: 'save' });
  bridge.receive({ jsonrpc: '2.0', id: request.id, result: '256' });
  assert.equal(await read, '256');
  await assert.rejects(bridge.localStorage.length(), error => error.code === 'STORAGE_UNSUPPORTED');
  const write = bridge.localStorage.setItem('save', '257');
  await Promise.resolve();
  bridge.receive({ jsonrpc: '2.0', id: messages.at(-1).id, error: { code: -32000, message: 'Disk full', data: { code: 'STORAGE_QUOTA_EXCEEDED', retryable: false } } });
  await assert.rejects(write, error => error.name === 'QuotaExceededError' && error.code === 'STORAGE_QUOTA_EXCEEDED');
  bridge.close();
  const unopened = new PlayweftBridge();
  const waiting = unopened.ready(); unopened.close();
  await assert.rejects(waiting, /closed/);
  delete globalThis.window;
});
